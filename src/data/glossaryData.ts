export function findGrammarTermByText(text: string): GrammarTerm | undefined {
  const normalized = text.trim();
  return GRAMMAR_GLOSSARY.find(
    (g) =>
      g.id === normalized ||
      g.termUr === normalized ||
      g.termAr === normalized ||
      g.aliases.some((a) => a === normalized)
  );
}
